-- 1. สร้างตารางผู้ใช้งาน
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL,
  fullname TEXT,
  department TEXT,
  role TEXT DEFAULT 'Staff',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. สร้างตารางเอกสาร
CREATE TABLE IF NOT EXISTS docs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  docNo TEXT,
  subject TEXT,
  signDate TEXT,
  fiscalYear TEXT,
  category TEXT,
  department TEXT,
  ownerId BIGINT,
  files JSONB DEFAULT '[]'::jsonb,
  confidential BOOLEAN DEFAULT false,
  password TEXT DEFAULT '',
  history JSONB DEFAULT '[]'::jsonb,
  createdAt TIMESTAMPTZ DEFAULT NOW(),
  updatedAt TIMESTAMPTZ DEFAULT NOW()
);

-- 3. สร้างตารางพนักงาน (ทะเบียนพนักงาน)
CREATE TABLE IF NOT EXISTS employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT,
  fullname TEXT,
  nickname TEXT,
  gender TEXT,
  idCard TEXT,
  enName TEXT,
  nationality TEXT,
  birthdate TEXT,
  religion TEXT,
  position TEXT,
  department TEXT,
  empType TEXT,
  salary NUMERIC DEFAULT 0,
  salaryType TEXT,
  startDate TEXT,
  status TEXT,
  phone TEXT,
  email TEXT,
  lineId TEXT,
  address TEXT,
  photo TEXT,
  updatedAt TIMESTAMPTZ DEFAULT NOW()
);

-- 4. สร้างตารางตั้งค่าระบบ
CREATE TABLE IF NOT EXISTS settings (
  id TEXT PRIMARY KEY,
  value JSONB NOT NULL
);

-- 5. สร้างตารางประกาศประจำวัน
CREATE TABLE IF NOT EXISTS announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text TEXT,
  at TIMESTAMPTZ DEFAULT NOW(),
  acks JSONB DEFAULT '[]'::jsonb
);

-- 6. สร้างตารางสถิติยอดถังน้ำ
CREATE TABLE IF NOT EXISTS waterstats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month TEXT,
  delivered INTEGER DEFAULT 0,
  outstanding INTEGER DEFAULT 0
);

