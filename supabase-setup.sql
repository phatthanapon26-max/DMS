-- ============================================================
-- RLS (Row Level Security) — เปิดให้ Anon เข้าถึงได้ (ระบบภายในองค์กร)
-- หมายเหตุ: ถ้าต้องการความปลอดภัยสูงกว่านี้ ให้ใช้ Supabase Auth แทน
